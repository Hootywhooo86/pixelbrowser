# Forward is back, mirrored.
ICONS["forward"] = [row[::-1] for row in ICONS["back"]]


def draw(rows):
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), rows
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == "#":
                img.putpixel((x, y), (255, 255, 255, 255))
    return img


def main():
    MOBILE.mkdir(parents=True, exist_ok=True)
    for name, rows in sorted(ICONS.items()):
        img = draw(rows)
        img.resize((48, 48), Image.NEAREST).save(MOBILE / f"{name}.png")
        big = img.resize((96, 96), Image.NEAREST)
        big.save(MOBILE / f"{name}@2x.png")
    # Desktop: CSS masks must be same-origin, which file:// pages aren't, so the
    # shell gets the icons as data: URLs in custom properties (icons.css).
    css = ["/* Generated by scripts/make-pixel-icons.py. Pixel icons as CSS masks. */", ":root {"]
    for name, rows in sorted(ICONS.items()):
        buf = io.BytesIO()
        draw(rows).resize((64, 64), Image.NEAREST).save(buf, "PNG", optimize=True)
        css.append(f"  --icon-{name}: url(data:image/png;base64,{base64.b64encode(buf.getvalue()).decode()});")
    css.append("}")
    DESKTOP_CSS.write_text("\n".join(css) + "\n")
    print(f"wrote {len(ICONS)} icons")


if __name__ == "__main__":
    main()
